function text(result: JcsCanonicalizationResult | ProjectCanonicalizationResult): string {
  assert.equal(result.kind, 'canonicalized');
  if (result.kind !== 'canonicalized') throw new Error('Expected canonicalized fixture.');
  return result.canonicalText;
}
function denied(result: JcsCanonicalizationResult | ProjectCanonicalizationResult): void {
  assert.equal(result.executionPermission, 'NOT_GRANTED');
  assert.equal(result.persistencePermission, 'NOT_GRANTED');
  assert.equal(result.semanticAdmission, 'NOT_EVALUATED');
  assert.equal(result.trustedAdmission, 'NOT_IMPLEMENTED');
  assert.equal(Object.hasOwn(result, 'digest'), false);
  assert.equal(Object.hasOwn(result, 'trustedValue'), false);
}
function error(result: JcsCanonicalizationResult | ProjectCanonicalizationResult, code?: string): void {
  assert.equal(result.kind, 'canonicalization-error');
  assert.equal(Object.hasOwn(result, 'canonicalText'), false);
  denied(result);
  if (result.kind === 'canonicalization-error') {
    assert.equal(result.diagnostics.length, 1);
    if (code) assert.equal(result.diagnostics[0].code, code);
    assert.ok(Object.isFrozen(result.diagnostics));
  }
}
